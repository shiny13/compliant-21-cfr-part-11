using System.Text.Json;
using RecordAuditTrails.Core.Exceptions;
using RecordAuditTrails.Core.Reporting;

namespace RecordAuditTrails.Core.Tests;

public class ReportFormatterTests
{
    [Fact]
    public void Json_ContainsRecordIntegrityAndFullEntries()
    {
        var json = new JsonReportFormatter().Render(TestData.Report());
        using var doc = JsonDocument.Parse(json);
        var root = doc.RootElement;

        Assert.Equal("reviewer", root.GetProperty("generatedBy").GetString());
        Assert.Equal("BatchRecord", root.GetProperty("record").GetProperty("recordType").GetString());
        Assert.True(root.GetProperty("integrity").GetProperty("isValid").GetBoolean());
        var entries = root.GetProperty("auditTrail");
        Assert.Equal(3, entries.GetArrayLength());
        Assert.Equal("Create", entries[0].GetProperty("action").GetString());
        Assert.Equal("=SUM(A1)", entries[1].GetProperty("newValue").GetString());
        Assert.False(string.IsNullOrEmpty(entries[2].GetProperty("hash").GetString()));
        Assert.Equal("application/json", new JsonReportFormatter().ContentType);
        Assert.Equal(ExportFormat.Json, new JsonReportFormatter().Format);
        Assert.Equal("json", new JsonReportFormatter().FileExtension);
    }

    [Fact]
    public void Csv_HasHeaderOneRowPerEntryAndEscapesCells()
    {
        var csv = new CsvReportFormatter().Render(TestData.Report());
        var lines = csv.TrimEnd('\r', '\n').Split("\r\n");
        Assert.Equal(4, lines.Length);
        Assert.StartsWith("Sequence,Timestamp (UTC),Action,Field,Old Value,New Value,Reason", lines[0]);
        Assert.Contains("'=SUM(A1)", lines[2]); // formula neutralized
        Assert.Contains("<script>alert(1)</script>", lines[3]);
        Assert.Equal("text/csv", new CsvReportFormatter().ContentType);
        Assert.Equal(ExportFormat.Csv, new CsvReportFormatter().Format);
        Assert.Equal("csv", new CsvReportFormatter().FileExtension);
    }

    [Theory]
    [InlineData(null, "")]
    [InlineData("plain", "plain")]
    [InlineData("a,b", "\"a,b\"")]
    [InlineData("say \"hi\"", "\"say \"\"hi\"\"\"")]
    [InlineData("line\nbreak", "\"line\nbreak\"")]
    [InlineData("+1", "'+1")]
    [InlineData("-1", "'-1")]
    [InlineData("@x", "'@x")]
    [InlineData("", "")]
    public void Csv_Cell(string? input, string expected) => Assert.Equal(expected, CsvReportFormatter.Cell(input));

    [Fact]
    public void Text_IsHumanReadableAndShowsOldAndNewValues()
    {
        var text = new TextReportFormatter().Render(TestData.Report());
        Assert.Contains("ELECTRONIC RECORD AND AUDIT TRAIL REPORT", text);
        Assert.Contains("Generated by    : reviewer", text);
        Assert.Contains("Audit trail verified: 3 entries, hash chain intact.", text);
        Assert.Contains("pH = 7.2", text);
        Assert.Contains("Note = (none)", text);
        Assert.Contains("Deleted         : No", text);
        Assert.Contains("Old    : (none)", text);
        Assert.Contains("New    : new1", text);
        Assert.Contains("Reason : Because of testing", text);
        Assert.Equal("text/plain", new TextReportFormatter().ContentType);
        Assert.Equal(ExportFormat.Text, new TextReportFormatter().Format);
        Assert.Equal("txt", new TextReportFormatter().FileExtension);
    }

    [Fact]
    public void Text_ReportsIntegrityFailureAndDeletedFlag()
    {
        var text = new TextReportFormatter().Render(TestData.Report(valid: false, deleted: true));
        Assert.Contains("AUDIT TRAIL INTEGRITY FAILURE at position 2", text);
        Assert.Contains("Deleted         : Yes", text);
    }

    [Fact]
    public void Html_EncodesRecordedValuesToPreventScriptInjection()
    {
        var html = new HtmlReportFormatter().Render(TestData.Report());
        Assert.DoesNotContain("<script>", html);
        Assert.Contains("&lt;script&gt;alert(1)&lt;/script&gt;", html);
        Assert.Contains("Batch &lt;1&gt;", html);
        Assert.Contains("Audit trail verified: 3 entries", html);
        Assert.Equal("text/html", new HtmlReportFormatter().ContentType);
        Assert.Equal(ExportFormat.Html, new HtmlReportFormatter().Format);
        Assert.Equal("html", new HtmlReportFormatter().FileExtension);
    }

    [Fact]
    public void Html_ReportsIntegrityFailureAndDeletedFlag()
    {
        var html = new HtmlReportFormatter().Render(TestData.Report(valid: false, deleted: true));
        Assert.Contains("class=\"bad\"", html);
        Assert.Contains("<th>Deleted</th><td>Yes</td>", html);
    }
}

public class ReportExporterTests
{
    [Theory]
    [InlineData(ExportFormat.Json, "json")]
    [InlineData(ExportFormat.Csv, "csv")]
    [InlineData(ExportFormat.Text, "txt")]
    [InlineData(ExportFormat.Html, "html")]
    public void Export_RendersEveryFormatWithMatchingDigest(ExportFormat format, string extension)
    {
        var report = TestData.Report();
        var exported = ReportExporter.CreateDefault().Export(report, format);

        Assert.EndsWith("." + extension, exported.FileName);
        Assert.Contains(report.Record.Id.ToString("N"), exported.FileName);
        Assert.Equal(Hashing.CanonicalHasher.Sha256Hex(exported.Content), exported.Sha256);
        Assert.NotEmpty(exported.ContentType);
    }

    [Fact]
    public void Export_ThrowsForUnregisteredFormat() =>
        Assert.Throws<AuditValidationException>(() => new ReportExporter([]).Export(TestData.Report(), ExportFormat.Json));

    [Theory]
    [InlineData("json", true)]
    [InlineData("CSV", true)]
    [InlineData("Html", true)]
    [InlineData("pdf", false)]
    [InlineData("42", false)]
    [InlineData(null, false)]
    public void TryParseFormat_AcceptsOnlyKnownNames(string? value, bool expected) =>
        Assert.Equal(expected, ReportExporter.TryParseFormat(value, out _));
}
