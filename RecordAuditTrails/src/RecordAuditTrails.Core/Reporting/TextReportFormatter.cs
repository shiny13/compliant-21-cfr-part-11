using System.Text;
using RecordAuditTrails.Core.Hashing;

namespace RecordAuditTrails.Core.Reporting;

/// <summary>Plain-text, human-readable copy of the record and its audit trail.</summary>
public sealed class TextReportFormatter : IAuditReportFormatter
{
    public ExportFormat Format => ExportFormat.Text;

    public string ContentType => "text/plain";

    public string FileExtension => "txt";

    public string Render(AuditReport report)
    {
        var r = report.Record;
        var sb = new StringBuilder();
        sb.AppendLine("ELECTRONIC RECORD AND AUDIT TRAIL REPORT");
        sb.AppendLine(new string('=', 60));
        sb.AppendLine($"Generated (UTC) : {TimestampPrecision.Format(report.GeneratedUtc)}");
        sb.AppendLine($"Generated by    : {report.GeneratedBy}");
        sb.AppendLine();
        sb.AppendLine("RECORD");
        sb.AppendLine(new string('-', 60));
        sb.AppendLine($"Id              : {r.Id}");
        sb.AppendLine($"Type            : {r.RecordType}");
        sb.AppendLine($"Title           : {r.Title}");
        sb.AppendLine($"Version         : {r.Version}");
        sb.AppendLine($"Deleted         : {(r.IsDeleted ? "Yes" : "No")}");
        sb.AppendLine($"Created         : {TimestampPrecision.Format(r.CreatedUtc)} by {r.CreatedBy}");
        sb.AppendLine($"Last modified   : {TimestampPrecision.Format(r.ModifiedUtc)} by {r.ModifiedBy}");
        sb.AppendLine($"Retain until    : {TimestampPrecision.Format(r.RetainUntilUtc)}");
        sb.AppendLine("Fields:");
        foreach (var (name, value) in r.Fields.OrderBy(f => f.Key, StringComparer.Ordinal))
        {
            sb.AppendLine($"  {name} = {value ?? "(none)"}");
        }
        sb.AppendLine();
        sb.AppendLine("INTEGRITY");
        sb.AppendLine(new string('-', 60));
        sb.AppendLine(report.Integrity.IsValid
            ? $"Audit trail verified: {report.Integrity.ItemsChecked} entries, hash chain intact."
            : $"AUDIT TRAIL INTEGRITY FAILURE at position {report.Integrity.FirstBrokenPosition}: {report.Integrity.Problem}");
        sb.AppendLine();
        sb.AppendLine("AUDIT TRAIL");
        sb.AppendLine(new string('-', 60));
        foreach (var e in report.Entries)
        {
            sb.AppendLine($"#{e.Sequence} {TimestampPrecision.Format(e.TimestampUtc)}  {e.Action}  {e.FieldName}");
            sb.AppendLine($"    By     : {e.Username} ({e.Role}, id {e.UserId})");
            sb.AppendLine($"    Old    : {e.OldValue ?? "(none)"}");
            sb.AppendLine($"    New    : {e.NewValue ?? "(none)"}");
            sb.AppendLine($"    Reason : {e.Reason}");
        }
        return sb.ToString();
    }
}
